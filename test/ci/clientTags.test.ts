import { describe, it, expect } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'
import { extractClaudeCodeTags, skillListingDrift } from '../../scripts/client-tags.js'
import { CLAUDE_CODE_TAGS } from '../../src/detection/clientTags.js'

// A minified Claude Code bundle in miniature: tag constants declared together,
// arrays of them (one with a spread, the anchor list with "system-reminder"),
// a constant only ever used through a helper, and a template far away.
const bundle = [
  'var junk="not-a-tag-list",zz="far-away";',
  'var du="command-name",Jy="command-message",e7t="skill-format",HH="task-id",lEe="bash-input",FH="bash-stdout",lft=[lEe,FH],s7="tick";',
  'function bi(){return 1}var _je="output-file";',
  'a7=[...lft,du,Jy,s7,"system-reminder","system_reminder","function_results"],wDi=[s7,"user-memory-input",du];',
  'x'.repeat(50_000),
  // biome-ignore lint/suspicious/noTemplateCurlyInString: literal minified-bundle fixture
  'function zUs(e){return[`<${Jy}>${e}</${Jy}>`,`<${e7t}>true</${e7t}>`].join("\\n")}',
  'const meta={README_URL:"https://example.invalid",VERSION:"9.8.7",FEEDBACK_CHANNEL:"x"};',
].join('')

describe('extracting the tags Claude Code wraps its own text in', () => {
  it('resolves the anchor list, its spreads, sibling lists, the constant block and templates', () => {
    const { version, tags } = extractClaudeCodeTags(bundle)
    expect(version).toBe('9.8.7')
    expect(tags).toEqual([
      'bash-input', 'bash-stdout', 'command-message', 'command-name', 'function_results', 'output-file',
      'skill-format', 'system-reminder', 'system_reminder', 'task-id', 'tick', 'user-memory-input',
    ])
  })

  // Claude Code 2.1.319 put 'linux' in the list, and earlier releases
  // 'nodejs': a one-letter name was declared in the region with an ordinary
  // word, and another scope's loop variable of the same name sat in a
  // `<${n}>` template. The minifier reuses one-letter names everywhere.
  it('ignores a far template whose constant has a one-letter name', () => {
    const reused = bundle
      .replace('var junk=', 'var n="linux",e="nodejs";var junk=')
      // biome-ignore lint/suspicious/noTemplateCurlyInString: literal minified-bundle fixture
      .replace('function zUs(e){', 'function zUs(e){for(let n of e)if(e.includes(`<${n}>`))return`<${e}>`;')
    const { tags } = extractClaudeCodeTags(reused)
    expect(tags).not.toContain('linux')
    expect(tags).not.toContain('nodejs')
    expect(tags).toEqual(extractClaudeCodeTags(bundle).tags)
  })

  it('fails instead of guessing when the anchor list is gone', () => {
    expect(() => extractClaudeCodeTags(bundle.replace('"system-reminder","system_reminder"', '"system-reminder"'))).toThrow(/anchor/)
  })

  it('keeps the committed list generated, sorted and holding the tags the detection relies on', () => {
    const file = fs.readFileSync(path.join(__dirname, '..', '..', 'src', 'detection', 'clientTags.ts'), 'utf8')
    expect(file).toMatch(/^\/\/ GENERATED by `npm run client-tags` from Claude Code \d+\.\d+\.\d+\./)
    const listed = [...file.matchAll(/^ {2}'([^']+)',$/gm)].map(m => m[1])
    expect(listed).toEqual([...listed].sort())
    expect(listed.length).toBe(CLAUDE_CODE_TAGS.size)
    for (const t of ['task-notification', 'skill-format', 'bash-stdout', 'local-command-caveat', 'system-reminder']) expect(CLAUDE_CODE_TAGS.has(t)).toBe(true)
  })
})

// #753: dropSkills finds Claude Code's skill listing by the sentence it
// starts with. The sentence is a template in the bundle; this is it, as
// 2.1.321 has it, with the minifier's names.
describe('the skill listing sentence in a Claude Code build', () => {
  const template = [
    'skill_listing:(e)=>{if(!e.content)return[];let[n,r]=e.addsToEarlier===!0?["also ",". This list adds to the skills listed earlier in this conversation and is not the full list"]:["",""];',
    // biome-ignore lint/suspicious/noTemplateCurlyInString: literal minified-bundle fixture
    'return Tu([De({content:de()&&Wi()?`The following skills are ${n}available; a script loads one with \\`await tools.Skill({skill: "name"})\\`, and its instructions arrive as a message right after the script\'s result${r}:\n\n${e.content}`',
    // biome-ignore lint/suspicious/noTemplateCurlyInString: literal minified-bundle fixture
    ':`The following skills are ${n}available for use with the Skill tool${r}:\n\n${e.content}`,isMeta:!0})])},',
  ].join('')

  it('finds every part the Tool Filter matches on', () => {
    expect(skillListingDrift(`x${template}y`)).toEqual([])
    // A minifier that escapes the line breaks, or renames the variables, is the same sentence.
    // biome-ignore lint/suspicious/noTemplateCurlyInString: literal minified-bundle fixture
    expect(skillListingDrift(template.replaceAll(':\n\n${e.content}', ':\\n\\n${$a.content}').replaceAll('${n}', '${q$}'))).toEqual([])
  })

  it('names the part a release changed', () => {
    expect(skillListingDrift(template.replace('for use with the Skill tool', 'through the Skill tool'))).toEqual([expect.stringContaining('for use with the Skill tool')])
    expect(skillListingDrift(template.replace('"also "', '"additionally "'))).toEqual([expect.stringContaining('also')])
    // biome-ignore lint/suspicious/noTemplateCurlyInString: literal minified-bundle fixture
    expect(skillListingDrift(template.replaceAll(':\n\n${e.content}', ':\n${e.content}'))).toHaveLength(2)
    expect(skillListingDrift('no listing here')).toHaveLength(3)
  })
})
