import { describe, it, expect } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'
import { extractClaudeCodeTags } from '../../scripts/client-tags.js'
import { CLAUDE_CODE_TAGS } from '../../src/detection/clientTags.js'

// A minified Claude Code bundle in miniature: tag constants declared together,
// arrays of them (one with a spread, the anchor list with "system-reminder"),
// a constant only ever used through a helper, and a template far away.
const bundle = [
  'var junk="not-a-tag-list",zz="far-away";',
  'var du="command-name",Jy="command-message",e7t="skill-format",HH="task-id",lEe="bash-input",FH="bash-stdout",lft=[lEe,FH],s7="tick";',
  'function bi(){return 1}var _je="output-file";',
  'a7=[...lft,du,Jy,s7,"system-reminder","system_reminder","function_results"],wDi=[s7,"user-memory-input",du];',
  'x'.repeat(50_000),
  // biome-ignore lint/suspicious/noTemplateCurlyInString: literal minified-bundle fixture
  'function zUs(e){return[`<${Jy}>${e}</${Jy}>`,`<${e7t}>true</${e7t}>`].join("\\n")}',
  'const meta={README_URL:"https://example.invalid",VERSION:"9.8.7",FEEDBACK_CHANNEL:"x"};',
].join('')

describe('extracting the tags Claude Code wraps its own text in', () => {
  it('resolves the anchor list, its spreads, sibling lists, the constant block and templates', () => {
    const { version, tags } = extractClaudeCodeTags(bundle)
    expect(version).toBe('9.8.7')
    expect(tags).toEqual([
      'bash-input', 'bash-stdout', 'command-message', 'command-name', 'function_results', 'output-file',
      'skill-format', 'system-reminder', 'system_reminder', 'task-id', 'tick', 'user-memory-input',
    ])
  })

  it('fails instead of guessing when the anchor list is gone', () => {
    expect(() => extractClaudeCodeTags(bundle.replace('"system-reminder","system_reminder"', '"system-reminder"'))).toThrow(/anchor/)
  })

  it('keeps the committed list generated, sorted and holding the tags the detection relies on', () => {
    const file = fs.readFileSync(path.join(__dirname, '..', '..', 'src', 'detection', 'clientTags.ts'), 'utf8')
    expect(file).toMatch(/^\/\/ GENERATED by `npm run client-tags` from Claude Code \d+\.\d+\.\d+\./)
    const listed = [...file.matchAll(/^ {2}'([^']+)',$/gm)].map(m => m[1])
    expect(listed).toEqual([...listed].sort())
    expect(listed.length).toBe(CLAUDE_CODE_TAGS.size)
    for (const t of ['task-notification', 'skill-format', 'bash-stdout', 'local-command-caveat', 'system-reminder']) expect(CLAUDE_CODE_TAGS.has(t)).toBe(true)
  })
})
